    /// <summary>
    /// Shared materials, generated by ProjectSetup. Nearly everything uses one material, because
    /// colour lives in the mesh, which keeps draw calls low on phones.
    /// </summary>
    public static class Mats
    {
        private static readonly Dictionary<Color, Material> OverlayCache = new Dictionary<Color, Material>();
        private static readonly Dictionary<Color, Material> OnTopCache = new Dictionary<Color, Material>();
        private static readonly int BaseColor = Shader.PropertyToID("_BaseColor");
        private static Material _world;
        private static Material _ground;
        private static Material _water;
        private static Material _particle;

        public static Material World => _world != null ? _world : (_world = Load("Art/WorldMat"));
        public static Material Ground => _ground != null ? _ground : (_ground = Load("Art/GroundMat"));
        public static Material Water => _water != null ? _water : (_water = Load("Art/WaterMat"));
        public static Material Particle => _particle != null ? _particle : (_particle = Load("Art/ParticleMat"));

        private static Material Load(string path)
        {
            var material = Resources.Load<Material>(path);
            if (material == null) throw new InvalidOperationException($"Missing {path}. Run Shinobi Dominion > Run Project Setup.");
            return material;
        }

        public static Material Overlay(Color color)
        {
            if (OverlayCache.TryGetValue(color, out var cached) && cached != null) return cached;
            var template = Resources.Load<Material>("Materials/PlaceholderOverlay");
            Material material;
            if (template != null)
            {
                material = new Material(template);
            }
            else
            {
                material = new Material(Shader.Find("Universal Render Pipeline/Unlit"));
                MakeTransparent(material);
            }
            material.SetColor(BaseColor, color);
            OverlayCache[color] = material;
            return material;
        }

        /// <summary>Always drawn over buildings. Used for cell feedback that must not be hidden.</summary>
        public static Material OnTop(Color color)
        {
            if (OnTopCache.TryGetValue(color, out var cached) && cached != null) return cached;
            var template = Resources.Load<Material>("Materials/PlaceholderOnTop");
            var material = template != null
                ? new Material(template)
                : new Material(Shader.Find("ShinobiDominion/OverlayOnTop"));
            material.SetColor(BaseColor, color);
            OnTopCache[color] = material;
            return material;
        }

        public static void MakeTransparent(Material material)
        {
            material.SetFloat("_Surface", 1f);
            material.SetFloat("_Blend", 0f);
            material.SetFloat("_SrcBlend", (float)BlendMode.SrcAlpha);
            material.SetFloat("_DstBlend", (float)BlendMode.OneMinusSrcAlpha);
            material.SetFloat("_ZWrite", 0f);
            material.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
            material.SetOverrideTag("RenderType", "Transparent");
            material.renderQueue = (int)RenderQueue.Transparent;
        }
    }

    /// <summary>
    /// Builds world meshes with colour in the vertices. Curved roofs, round pillars and soft blobs
    /// are all real geometry here, with surface detail coming from the shader's texture array.
    /// </summary>
    public sealed class MeshBuilder
    {
        private readonly List<Vector3> _vertices = new List<Vector3>();
        private readonly List<Vector3> _normals = new List<Vector3>();
        private readonly List<Color> _colors = new List<Color>();
        private readonly List<Vector3> _uv0 = new List<Vector3>();
        private readonly List<Vector2> _uv1 = new List<Vector2>();
        private readonly List<int> _triangles = new List<int>();

        /// <summary>Darkens geometry close to the ground, a cheap stand-in for ambient occlusion.</summary>
        public bool ContactShade = true;

        /// <summary>What curved roofs are made of. Set by the building's skin.</summary>
        public ArtSurface RoofSurface = ArtSurface.Tile;

        /// <summary>Soft painted light: darker at the foot of a building and brighter towards the top.</summary>
        public void ShadeByHeight(float bottom, float top)
        {
            var height = Mathf.Max(MaxY, 0.01f);
            for (var i = 0; i < _colors.Count; i++)
            {
                var factor = Mathf.Lerp(bottom, top, Mathf.Clamp01(_vertices[i].y / height));
                var c = _colors[i];
                _colors[i] = new Color(c.r * factor, c.g * factor, c.b * factor, c.a);
            }
        }

        /// <summary>The highest point of the mesh close to a spot on the ground.</summary>
        public float MaxYNear(float x, float z, float radius)
        {
            var max = 0f;
            foreach (var vertex in _vertices)
            {
                var dx = vertex.x - x;
                var dz = vertex.z - z;
                if (dx * dx + dz * dz <= radius * radius) max = Mathf.Max(max, vertex.y);
            }
            return max;
        }

        public float MaxY
        {
            get
            {
                var max = 0f;
                foreach (var vertex in _vertices) max = Mathf.Max(max, vertex.y);
                return max;
            }
        }

        public int VertexCount => _vertices.Count;

        private static float ScaleFor(ArtSurface surface)
        {
            switch (surface)
            {
                case ArtSurface.Stone: return 0.7f;
                case ArtSurface.Wood: return 0.9f;
                case ArtSurface.Tile: return 0.85f;
                case ArtSurface.Plaster: return 0.6f;
                case ArtSurface.Grass: return 1.1f;
                case ArtSurface.Dirt: return 0.7f;
                case ArtSurface.Marble: return 0.5f;
                case ArtSurface.Metal: return 0.7f;
                case ArtSurface.Thatch: return 0.8f;
                case ArtSurface.Rock: return 0.45f;
                default: return 1f;
            }
        }

        private void Vertex(Vector3 position, Vector3 normal, Color color, Vector2 uv, ArtSurface surface, float sway, float glow)
        {
            _vertices.Add(position);
            _normals.Add(normal);
            _colors.Add(color.linear);
            _uv0.Add(new Vector3(uv.x, uv.y, (int)surface));
            _uv1.Add(new Vector2(sway, glow));
        }

        /// <summary>Adds a flat quad, flipping winding if needed so it faces <paramref name="outward"/>.</summary>
        public void Quad(Vector3 a, Vector3 b, Vector3 c, Vector3 d, Vector3 outward, Color color,
            ArtSurface surface = ArtSurface.Plain, float sway = 0f, float glow = 0f)
        {
            var normal = Vector3.Cross(b - a, c - a).normalized;
            if (normal == Vector3.zero) normal = Vector3.Cross(c - a, d - a).normalized;
            if (Vector3.Dot(normal, outward) < 0f)
            {
                (b, d) = (d, b);
                normal = -normal;
            }

            var scale = ScaleFor(surface);
            var u = (b - a).magnitude * scale;
            var v = (d - a).magnitude * scale;
            var start = _vertices.Count;
            Vertex(a, normal, color, new Vector2(0f, 0f), surface, sway, glow);
            Vertex(b, normal, color, new Vector2(u, 0f), surface, sway, glow);
            Vertex(c, normal, color, new Vector2(u, v), surface, sway, glow);
            Vertex(d, normal, color, new Vector2(0f, v), surface, sway, glow);
            AddQuadIndices(start);
        }

        private void AddQuadIndices(int start)
        {
            _triangles.Add(start);
            _triangles.Add(start + 1);
            _triangles.Add(start + 2);
            _triangles.Add(start);
            _triangles.Add(start + 2);
            _triangles.Add(start + 3);
        }

        /// <summary>Axis-aligned box. <paramref name="baseCenter"/> is the centre of its bottom face. The bottom is not drawn.</summary>
        public void Box(Vector3 baseCenter, Vector3 size, Color color, ArtSurface surface = ArtSurface.Plain, float sway = 0f, float glow = 0f) =>
            Frustum(baseCenter, size.x, size.z, size.x, size.z, size.y, color, surface, sway, glow);

        /// <summary>A tapered block: foundations, steps and mounds. Top size 0 makes a pyramid.</summary>
        public void Frustum(Vector3 baseCenter, float bottomX, float bottomZ, float topX, float topZ, float height, Color color,
            ArtSurface surface = ArtSurface.Plain, float sway = 0f, float glow = 0f)
        {
            var bx = bottomX * 0.5f;
            var bz = bottomZ * 0.5f;
            var tx = topX * 0.5f;
            var tz = topZ * 0.5f;
            var up = Vector3.up * height;

            var b0 = baseCenter + new Vector3(-bx, 0f, -bz);
            var b1 = baseCenter + new Vector3(bx, 0f, -bz);
            var b2 = baseCenter + new Vector3(bx, 0f, bz);
            var b3 = baseCenter + new Vector3(-bx, 0f, bz);
            var t0 = baseCenter + up + new Vector3(-tx, 0f, -tz);
            var t1 = baseCenter + up + new Vector3(tx, 0f, -tz);
            var t2 = baseCenter + up + new Vector3(tx, 0f, tz);
            var t3 = baseCenter + up + new Vector3(-tx, 0f, tz);

            Quad(b0, b1, t1, t0, Vector3.back, color, surface, sway, glow);
            Quad(b1, b2, t2, t1, Vector3.right, color, surface, sway, glow);
            Quad(b2, b3, t3, t2, Vector3.forward, color, surface, sway, glow);
            Quad(b3, b0, t0, t3, Vector3.left, color, surface, sway, glow);
            if (topX > 0f && topZ > 0f) Quad(t0, t1, t2, t3, Vector3.up, color, surface, sway, glow);
        }

        /// <summary>A round pillar or cone, smooth-shaded. Radius 0 at the top makes a cone.</summary>
        public void Cylinder(Vector3 baseCenter, float radiusBottom, float radiusTop, float height, int sides, Color color,
            ArtSurface surface = ArtSurface.Plain, float sway = 0f, float glow = 0f, bool cap = true)
        {
            var scale = ScaleFor(surface);
            var slope = (radiusBottom - radiusTop) / Mathf.Max(0.001f, height);
            var circumference = 2f * Mathf.PI * radiusBottom * scale;
            var first = _vertices.Count;
            for (var i = 0; i <= sides; i++)
            {
                var angle = (float)i / sides * Mathf.PI * 2f;
                var direction = new Vector3(Mathf.Cos(angle), 0f, Mathf.Sin(angle));
                var normal = (direction + Vector3.up * slope).normalized;
                var u = circumference * i / sides;
                Vertex(baseCenter + direction * radiusBottom, normal, color, new Vector2(u, 0f), surface, sway, glow);
                Vertex(baseCenter + direction * radiusTop + Vector3.up * height, normal, color, new Vector2(u, height * scale), surface, sway, glow);
            }
            for (var i = 0; i < sides; i++)
            {
                var a = first + i * 2;
                _triangles.Add(a);
                _triangles.Add(a + 1);
                _triangles.Add(a + 3);
                _triangles.Add(a);
                _triangles.Add(a + 3);
                _triangles.Add(a + 2);
            }

            if (cap && radiusTop > 0.001f)
            {
                var top = baseCenter + Vector3.up * height;
                for (var i = 0; i < sides; i++)
                {
                    var a0 = (float)i / sides * Mathf.PI * 2f;
                    var a1 = (float)(i + 1) / sides * Mathf.PI * 2f;
                    var p0 = top + new Vector3(Mathf.Cos(a0), 0f, Mathf.Sin(a0)) * radiusTop;
                    var p1 = top + new Vector3(Mathf.Cos(a1), 0f, Mathf.Sin(a1)) * radiusTop;
                    var start = _vertices.Count;
                    Vertex(top, Vector3.up, color, Vector2.zero, surface, sway, glow);
                    Vertex(p1, Vector3.up, color, Vector2.right, surface, sway, glow);
                    Vertex(p0, Vector3.up, color, Vector2.one, surface, sway, glow);
                    _triangles.Add(start);
                    _triangles.Add(start + 1);
                    _triangles.Add(start + 2);
                }
            }
        }

        /// <summary>A tapered rod between any two points: limbs, weapons, feathers. A negative end radius means no taper.</summary>
        public void Rod(Vector3 a, Vector3 b, float radius, int sides, Color color, ArtSurface surface = ArtSurface.Plain, float sway = 0f, float endRadius = -1f, float glow = 0f)
        {
            var axis = b - a;
            if (axis.sqrMagnitude < 0.000001f) return;
            var end = endRadius < 0f ? radius : endRadius;
            var forward = axis.normalized;
            var side = Vector3.Cross(forward, Mathf.Abs(forward.y) > 0.9f ? Vector3.forward : Vector3.up).normalized;
            var up = Vector3.Cross(side, forward);
            var scale = ScaleFor(surface);
            var length = axis.magnitude * scale;
            var first = _vertices.Count;
            for (var i = 0; i <= sides; i++)
            {
                var angle = (float)i / sides * Mathf.PI * 2f;
                var direction = side * Mathf.Cos(angle) + up * Mathf.Sin(angle);
                var u = i * radius * 2f * scale;
                Vertex(a + direction * radius, direction, color, new Vector2(u, 0f), surface, sway, glow);
                Vertex(b + direction * end, direction, color, new Vector2(u, length), surface, sway, glow);
            }
            for (var i = 0; i < sides; i++)
            {
                var v = first + i * 2;
                _triangles.Add(v);
                _triangles.Add(v + 1);
                _triangles.Add(v + 3);
                _triangles.Add(v);
                _triangles.Add(v + 3);
                _triangles.Add(v + 2);
            }
        }

        /// <summary>A soft rounded lump: foliage, heads, boulders. Jitter roughens the surface.</summary>
        public void Blob(Vector3 center, Vector3 radius, Color color, ArtSurface surface = ArtSurface.Plain,
            float sway = 0f, float glow = 0f, int segments = 8, int rings = 5, float jitter = 0f, int seed = 0, Color? top = null)
        {
            var random = jitter > 0f ? new System.Random(seed) : null;
            var offsets = new float[(rings + 1) * (segments + 1)];
            for (var r = 0; r <= rings; r++)
            for (var s = 0; s <= segments; s++)
            {
                var wrapped = s == segments ? 0 : s;
                var pole = r == 0 || r == rings;
                offsets[r * (segments + 1) + s] = random == null ? 1f
                    : wrapped != s ? offsets[r * (segments + 1)]
                    : pole ? 1f
                    : 1f + (float)(random.NextDouble() * 2.0 - 1.0) * jitter;
            }

            var scale = ScaleFor(surface);
            var upper = top ?? color;
            var first = _vertices.Count;
            for (var r = 0; r <= rings; r++)
            for (var s = 0; s <= segments; s++)
            {
                var polar = (float)r / rings * Mathf.PI;
                var azimuth = (float)s / segments * Mathf.PI * 2f;
                var direction = new Vector3(Mathf.Sin(polar) * Mathf.Cos(azimuth), Mathf.Cos(polar), Mathf.Sin(polar) * Mathf.Sin(azimuth));
                var normal = new Vector3(direction.x / Mathf.Max(radius.x, 0.001f), direction.y / Mathf.Max(radius.y, 0.001f), direction.z / Mathf.Max(radius.z, 0.001f)).normalized;
                var position = center + Vector3.Scale(direction, radius) * offsets[r * (segments + 1) + s];
                var tint = Color.Lerp(color, upper, Mathf.InverseLerp(center.y - radius.y, center.y + radius.y, position.y));
                var uv = surface == ArtSurface.Rock
                    ? new Vector2(position.x - position.z, position.y + (position.x + position.z) * 0.5f)
                    : new Vector2(position.x, position.z);
                Vertex(position, normal, tint, uv * scale, surface, sway, glow);
            }
            for (var r = 0; r < rings; r++)
            for (var s = 0; s < segments; s++)
            {
                var a = first + r * (segments + 1) + s;
                var b = a + 1;
                var d = a + segments + 1;
                var c = d + 1;
                _triangles.Add(a);
                _triangles.Add(b);
                _triangles.Add(c);
                _triangles.Add(a);
                _triangles.Add(c);
                _triangles.Add(d);
            }
        }

        /// <summary>
        /// A hip roof with a concave curve and upturned corners, the signature shape of the village.
        /// The top half sizes set the ridge, so narrow values make a long ridge line.
        /// </summary>
        public void Roof(Vector3 baseCenter, float halfX, float halfZ, float topHalfX, float topHalfZ, float rise, float upturn, Color color, Color trim)
        {
            const int rows = 4;
            const int segments = 6;
            Vector3 Point(int side, float u, float t)
            {
                var hx = Mathf.Lerp(halfX, topHalfX, t);
                var hz = Mathf.Lerp(halfZ, topHalfZ, t);
                float x;
                float z;
                switch (side)
                {
                    case 0: x = Mathf.Lerp(-hx, hx, u); z = -hz; break;
                    case 1: x = hx; z = Mathf.Lerp(-hz, hz, u); break;
                    case 2: x = Mathf.Lerp(hx, -hx, u); z = hz; break;
                    default: x = -hx; z = Mathf.Lerp(hz, -hz, u); break;
                }
                var corner = Mathf.Abs(2f * u - 1f);
                var lift = upturn * corner * corner * corner * (1f - t) * (1f - t);
                return baseCenter + new Vector3(x, rise * Mathf.Pow(t, 1.7f) + lift, z);
            }

            var outwards = new[] { Vector3.back, Vector3.right, Vector3.forward, Vector3.left };
            for (var side = 0; side < 4; side++)
            {
                for (var row = 0; row < rows; row++)
                for (var segment = 0; segment < segments; segment++)
                {
                    var t0 = (float)row / rows;
                    var t1 = (float)(row + 1) / rows;
                    var u0 = (float)segment / segments;
                    var u1 = (float)(segment + 1) / segments;
                    var vary = 0.94f + 0.12f * Mathf.Abs(Mathf.Sin(side * 12.9f + row * 78.2f + segment * 37.7f));
                    Quad(Point(side, u0, t0), Point(side, u1, t0), Point(side, u1, t1), Point(side, u0, t1),
                        outwards[side] + Vector3.up, new Color(color.r * vary, color.g * vary, color.b * vary), RoofSurface);
                }

                // A raised ridge down this corner of the roof, ending in a tile at the upturned tip.
                var ridge = Mathf.Min(0.035f + Mathf.Max(halfX, halfZ) * 0.012f, 0.06f);
                var ridgeColor = Color.Lerp(color, Color.black, 0.32f);
                for (var row = 0; row < rows; row++)
                {
                    var a = Point(side, 0f, (float)row / rows);
                    var b = Point(side, 0f, (float)(row + 1) / rows);
                    var across = Vector3.Cross(b - a, Vector3.up).normalized * ridge;
                    var lift = Vector3.up * ridge * 0.9f;
                    Quad(a - across, b - across, b + lift, a + lift, Vector3.up - across, ridgeColor, ArtSurface.Plain);
                    Quad(a + across, b + across, b + lift, a + lift, Vector3.up + across, ridgeColor, ArtSurface.Plain);
                }
                Blob(Point(side, 0f, 0f) + Vector3.up * ridge, Vector3.one * ridge * 1.5f, trim, ArtSurface.Plain, 0f, 0f, 5, 3);

                // Rafter ends along the eave.
                var rafters = Mathf.Clamp(Mathf.RoundToInt((side % 2 == 0 ? halfX : halfZ) * 4f), 3, 9);
                for (var i = 1; i < rafters; i++)
                {
                    var at = Point(side, (float)i / rafters, 0f) + Vector3.down * 0.09f;
                    var along = (Point(side, 0.6f, 0f) - Point(side, 0.4f, 0f)).normalized * 0.022f;
                    Quad(at - along, at + along, at + along + Vector3.down * 0.05f, at - along + Vector3.down * 0.05f, outwards[side], trim, ArtSurface.Wood);
                }

                // The eave board: a pale edge that picks the roof line out from a distance.
                for (var segment = 0; segment < segments; segment++)
                {
                    var u0 = (float)segment / segments;
                    var u1 = (float)(segment + 1) / segments;
                    var a = Point(side, u0, 0f);
                    var b = Point(side, u1, 0f);
                    var down = Vector3.down * 0.09f;
                    Quad(a + down, b + down, b, a, outwards[side], trim, ArtSurface.Wood);
                }
            }

            var capCenter = baseCenter + Vector3.up * rise;
            Box(capCenter - Vector3.up * 0.02f, new Vector3(topHalfX * 2f + 0.1f, 0.1f, topHalfZ * 2f + 0.1f), trim, ArtSurface.Wood);
        }

        public Mesh Build(string name)
        {
            if (ContactShade)
            {
                for (var i = 0; i < _colors.Count; i++)
                {
                    var factor = _vertices[i].y < -0.05f ? 1f : Mathf.Lerp(0.62f, 1f, Mathf.Clamp01(_vertices[i].y / 0.55f));
                    var c = _colors[i];
                    _colors[i] = new Color(c.r * factor, c.g * factor, c.b * factor, c.a);
                }
            }

            var mesh = new Mesh { name = name, indexFormat = IndexFormat.UInt32 };
            mesh.SetVertices(_vertices);
            mesh.SetNormals(_normals);
            mesh.SetColors(_colors);
            mesh.SetUVs(0, _uv0);
            mesh.SetUVs(1, _uv1);
            mesh.SetTriangles(_triangles, 0);
            mesh.RecalculateBounds();
            return mesh;
        }

        public Material[] LitMaterials() => new[] { Mats.World };
    }

